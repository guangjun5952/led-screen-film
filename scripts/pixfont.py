_imgs = {}

def _glyph_image(ch):
    im = _imgs.get(ch)
    if im is None:
        rows = _G.get(ch) or _G.get(ch.upper()) or _G['?']
        a = np.zeros((7, 5, 4), np.uint8)
        for y, r in enumerate(rows):
            for x, b in enumerate(r):
                if b == '1':
                    a[y, x] = 255
        im = skia.Image.fromarray(a, colorType=skia.ColorType.kRGBA_8888_ColorType)
        _imgs[ch] = im
    return im

def pix_width(s, scale=1):
    return len(s) * 6 * scale - scale

def pix_text(c, s, x, y, col, alpha=1.0, scale=1, align='left'):
    """y is the TOP of the glyph cell. integer-snapped. col=(r,g,b,a)."""
    if align == 'center':
        x -= pix_width(s, scale) / 2
    elif align == 'right':
        x -= pix_width(s, scale)
    x = round(x); y = round(y)
    p = skia.Paint()
    r, g, b, a = col
    p.setColorFilter(skia.ColorFilters.Blend(skia.Color4f(r, g, b, 1).toColor(), skia.BlendMode.kSrcIn))
    p.setAlphaf(max(0.0, min(1.0, alpha * a)))
    samp = skia.SamplingOptions(skia.FilterMode.kNearest)
    for i, ch in enumerate(s):
        if ch == ' ':
            continue
        im = _glyph_image(ch)
        dst = skia.Rect.MakeXYWH(x + i * 6 * scale, y, 5 * scale, 7 * scale)
        c.drawImageRect(im, dst, samp, p)
